/**
 * @swagger
 * /api/tasks:
 *   post:
 *     summary: Create a new task
 *     tags: [Tasks]
 *     security:
 *       - bearerAuth: []
 *     requestBody:
 *       required: true
 *       content:
 *         application/json:
 *           schema:
 *             type: object
 *             required:
 *               - title
 *               - description
 *               - assignedTo
 *             properties:
 *               title:
 *                 type: string
 *                 description: Task title
 *                 example: "Complete project documentation"
 *               description:
 *                 type: string
 *                 description: Task description
 *                 example: "Write comprehensive documentation for the new feature"
 *               assignedTo:
 *                 type: string
 *                 description: ID of the user to assign the task to
 *                 example: "507f1f77bcf86cd799439011"
 *               deadline:
 *                 type: string
 *                 format: date-time
 *                 description: Task deadline (optional)
 *                 example: "2024-12-31T23:59:59.000Z"
 *     responses:
 *       201:
 *         description: Task created successfully
 *         content:
 *           application/json:
 *             schema:
 *               type: object
 *               properties:
 *                 success:
 *                   type: boolean
 *                   example: true
 *                 message:
 *                   type: string
 *                   example: "Task created successfully"
 *                 data:
 *                   $ref: '#/components/schemas/Task'
 *       400:
 *         description: Bad request - validation error
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       401:
 *         description: Unauthorized - invalid or missing token
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 *       403:
 *         description: Forbidden - can only assign tasks to subordinates
 *         content:
 *           application/json:
 *             schema:
 *               $ref: '#/components/schemas/Error'
 */
router.post("/", taskController.createTask);

